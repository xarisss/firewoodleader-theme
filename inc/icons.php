/**
 * Αν ο χρήστης ανεβάσει δική του εικόνα για το εικονίδιο "flame" (λογότυπο),
 * ενημερώνει αυτόματα και το favicon (Site Icon) του WordPress ώστε να
 * ταιριάζουν πάντα.
 */
function fl_sync_favicon_with_flame_icon( $wp_customize ) {
	$flame_url = get_theme_mod( 'fl_icon_override_flame', '' );
	if ( ! $flame_url ) {
		return;
	}
	$attachment_id = attachment_url_to_postid( $flame_url );
	if ( $attachment_id ) {
		update_option( 'site_icon', $attachment_id );
	}
}
add_action( 'customize_save_after', 'fl_sync_favicon_with_flame_icon' );
